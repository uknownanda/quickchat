import express from "express";
import { protectRoute } from "../middleware/auth.js";
import { deleteMessage, togglePinMessage, getMessages, getUsersForSidebar, getSharedMedia, markMessageAsSeen, searchMessages, sendMessage, updateMessage, getConversationWallpaper, updateConversationWallpaper } from "../controllers/messageController.js";
import { createRateLimiter, validateObjectIdParam } from "../lib/security.js";

const messageRouter = express.Router();
const sendLimiter = createRateLimiter({ windowMs: 60 * 1000, max: 60, message: "You are sending messages too quickly. Please wait a moment." });
const searchLimiter = createRateLimiter({ windowMs: 60 * 1000, max: 30, message: "Too many searches. Please slow down." });
const validId = validateObjectIdParam("id");
messageRouter.get("/users", protectRoute, getUsersForSidebar);
messageRouter.get("/wallpaper/:id", protectRoute, validId, getConversationWallpaper);
messageRouter.put("/wallpaper/:id", protectRoute, validId, updateConversationWallpaper);
messageRouter.get("/search/:id", protectRoute, validId, searchLimiter, searchMessages);
messageRouter.get("/media/:id", protectRoute, validId, getSharedMedia);
messageRouter.get("/:id", protectRoute, validId, getMessages);
messageRouter.put("/mark/:id", protectRoute, validId, markMessageAsSeen);
messageRouter.post("/send/:id", protectRoute, validId, sendLimiter, sendMessage);
messageRouter.patch("/:id", protectRoute, validId, sendLimiter, updateMessage);
messageRouter.patch("/:id/pin", protectRoute, validId, sendLimiter, togglePinMessage);
messageRouter.delete("/:id", protectRoute, validId, sendLimiter, deleteMessage);
export default messageRouter;
